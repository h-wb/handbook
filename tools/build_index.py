"""Write INDEX.md: every page of every repo in registry.yaml, from its header.

Usage: uv run tools/build_index.py [--repos-dir DIR] [--today YYYY-MM-DD]

A repo is read from DIR/<id> (default: the parent of this repo), or from this
repo when its id is "handbook". A repo that is not checked out is listed as
not read; its pages are left out, not guessed.
"""
import argparse
import datetime
import pathlib
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parents[1]
INTERVALS = {"how-to": 90, "overview": 180, "reference": 180, "plan": 30}
REQUIRED = ("id", "type", "system", "status", "summary", "created")


def header(path):
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---\n"):
        return None
    end = text.find("\n---", 4)
    if end == -1:
        return None
    data = yaml.safe_load(text[4:end])
    return data if isinstance(data, dict) and "id" in data else None


def pages(repo_dir, roots):
    for root in roots:
        target = repo_dir / root
        files = [target] if target.is_file() else sorted(target.rglob("*.md"))
        for path in files:
            if path.name == "INDEX.md":
                continue
            data = header(path)
            if data is not None:
                yield path, data


def due(data, today):
    if data.get("status") in ("superseded", "archived") or data.get("type") == "decision":
        return ""
    reviewed = data.get("reviewed")
    if not isinstance(reviewed, datetime.date):
        return "never reviewed"
    interval = data.get("review_every") or INTERVALS.get(data.get("type"), 180)
    late = (today - reviewed).days - int(interval)
    return f"due, {late} days late" if late > 0 else ""


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--repos-dir", type=pathlib.Path, default=ROOT.parent)
    parser.add_argument("--today", type=datetime.date.fromisoformat, default=datetime.date.today())
    args = parser.parse_args()

    registry = yaml.safe_load((ROOT / "registry.yaml").read_text(encoding="utf-8"))
    systems = {s["id"] for s in registry["systems"]}
    rows, problems, unread, seen = [], [], [], {}
    for repo in registry["repos"]:
        repo_dir = ROOT if repo["id"] == "handbook" else args.repos_dir / repo["id"]
        if not repo_dir.is_dir():
            unread.append(repo["id"])
            continue
        for path, data in pages(repo_dir, repo.get("pages", [])):
            rel = path.relative_to(repo_dir).as_posix()
            link = rel if repo["id"] == "handbook" else f"{repo['url']}/blob/HEAD/{rel}"
            for key in REQUIRED:
                if not data.get(key):
                    problems.append(f"{repo['id']}/{rel}: no `{key}`")
            if data.get("system") not in systems:
                problems.append(f"{repo['id']}/{rel}: system `{data.get('system')}` is not in the registry")
            if data["id"] in seen:
                problems.append(f"{repo['id']}/{rel}: id `{data['id']}` is also used by {seen[data['id']]}")
            seen[data["id"]] = f"{repo['id']}/{rel}"
            rows.append((data, repo["id"], link, due(data, args.today)))

    def order(row):
        reviewed = row[0].get("reviewed")
        dated = isinstance(reviewed, datetime.date)
        return (0 if row[3] else 1, 0 if dated else 1, reviewed if dated else datetime.date.min, row[0]["id"])

    out = ["# Index", "", "Generated by `tools/build_index.py`. Do not edit.", "",
           "Pages due for review come first, then the longest unreviewed.", "",
           "| Page | Type | System | Status | Reviewed | Due | Repo |",
           "| --- | --- | --- | --- | --- | --- | --- |"]
    for data, repo_id, link, late in sorted(rows, key=order):
        summary = str(data.get("summary", "")).replace("|", "\\|")
        out.append(f"| [{data['id']}]({link}): {summary} | {data.get('type', '')} | {data.get('system', '')} "
                   f"| {data.get('status', '')} | {data.get('reviewed') or ''} | {late} | {repo_id} |")
    if unread:
        out += ["", "Not read (repo not checked out): " + ", ".join(unread) + "."]
    if problems:
        out += ["", "## Problems", ""] + [f"- {p}" for p in problems]
    (ROOT / "INDEX.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"{len(rows)} pages, {len(problems)} problems, {len(unread)} repos not read")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
